#!/usr/bin/env python3
"""Build the offline emergency places that ship inside the app.

Input: one Overpass JSON file per state and group in RAW_DIR, named
  XX-core.json  (hospitals, clinics, urgent care, police, fire, pharmacies, shelters)
  XX-water.json (drinking water and water points)
fetched with queries like:
  [out:json];area["ISO3166-2"="US-XX"]->.s;(nwr["amenity"="hospital"](area.s);...);out center tags;

Output: src/data/places/XX.ts (one compact string per state) and
src/data/places/index.ts (each state's bounding box and a loader).

Each line of a state's string is: kind code, longitude x 1e4, latitude x 1e4, name,
separated by tabs. Data (c) OpenStreetMap contributors, ODbL.

Usage: python3 -I tools/build-places.py RAW_DIR
"""
import json
import os
import sys

RAW = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'places')
os.makedirs(OUT, exist_ok=True)


def kind(tags):
    a = tags.get('amenity', '')
    if a == 'hospital':
        return 'H'
    if a == 'clinic' or tags.get('healthcare') == 'urgent_care':
        return 'U'
    if a == 'police':
        return 'P'
    if a == 'fire_station':
        return 'F'
    if a == 'pharmacy':
        return 'R'
    if tags.get('social_facility') == 'shelter' or tags.get('emergency') == 'assembly_point':
        return 'S'
    if a in ('drinking_water', 'water_point'):
        if tags.get('access') in ('private', 'no', 'customers'):
            return None
        return 'W'
    return None


def clean(name):
    return ' '.join(name.replace('\t', ' ').split())[:80]


states = {}
for f in sorted(os.listdir(RAW)):
    if not f.endswith('.json') or '-' not in f:
        continue
    code = f.split('-')[0]
    with open(os.path.join(RAW, f)) as fh:
        data = json.load(fh)
    places = states.setdefault(code, {})
    for el in data.get('elements', []):
        tags = el.get('tags') or {}
        k = kind(tags)
        if not k:
            continue
        lat = el.get('lat', (el.get('center') or {}).get('lat'))
        lon = el.get('lon', (el.get('center') or {}).get('lon'))
        if lat is None or lon is None:
            continue
        places[(el['type'], el['id'])] = (k, round(lon * 1e4), round(lat * 1e4), clean(tags.get('name', '')))

index = []
total = 0
for code, places in sorted(states.items()):
    # The same place is often mapped twice (a point and a building outline) a few
    # meters apart. Keep one per kind per ~50 m, preferring the one with a name.
    best = {}
    for r in places.values():
        key = (r[0], round(r[1] / 5), round(r[2] / 5))
        if key not in best or (not best[key][3] and r[3]):
            best[key] = r
    rows = sorted(best.values(), key=lambda r: (r[0], r[2], r[1]))
    if not rows:
        continue
    text = '\n'.join(f'{k}\t{lon}\t{lat}\t{name}' for k, lon, lat, name in rows)
    with open(os.path.join(OUT, f'{code}.ts'), 'w') as fh:
        fh.write('// Generated by tools/build-places.py. Data (c) OpenStreetMap contributors, ODbL.\n')
        fh.write(f'export default {json.dumps(text, ensure_ascii=False)};\n')
    lons = [r[1] / 1e4 for r in rows]
    lats = [r[2] / 1e4 for r in rows]
    index.append((code, [round(min(lons), 2), round(min(lats), 2), round(max(lons), 2), round(max(lats), 2)], len(rows)))
    total += len(rows)
    counts = {}
    for r in rows:
        counts[r[0]] = counts.get(r[0], 0) + 1
    print(code, len(rows), counts, f'{len(text) / 1024:.0f} KB')

with open(os.path.join(OUT, 'index.ts'), 'w') as fh:
    fh.write('// Generated by tools/build-places.py. Data (c) OpenStreetMap contributors, ODbL.\n')
    fh.write('/* eslint-disable @typescript-eslint/no-require-imports */\n\n')
    fh.write('export const PLACE_STATES: { code: string; bbox: number[]; count: number }[] = [\n')
    for code, bbox, n in index:
        fh.write(f"  {{ code: '{code}', bbox: {json.dumps(bbox)}, count: {n} }},\n")
    fh.write('];\n\n')
    fh.write('/** One state\'s places as a compact string, loaded only when needed. */\n')
    fh.write('export function loadPlaceData(code: string): string | null {\n  switch (code) {\n')
    for code, _, _ in index:
        fh.write(f"    case '{code}':\n      return require('./{code}').default;\n")
    fh.write('    default:\n      return null;\n  }\n}\n')
print('TOTAL', total, 'places in', len(index), 'states')
