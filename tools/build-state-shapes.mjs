// Builds src/data/state-shapes.ts: a small, simplified outline of every US
// state, so "Find me" can tell which state a GPS position is actually inside,
// with no internet. Source: us-atlas (US Census cartographic boundaries,
// public domain). Run from any folder that has the three packages installed:
//   npm i us-atlas@3 topojson-client@3 topojson-simplify@3
//   node tools/build-state-shapes.mjs <path to that folder's node_modules> src/data/state-shapes.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const [modules, out] = process.argv.slice(2);
const require = createRequire(path.resolve(modules, 'x.js'));
const { feature } = require('topojson-client');
const { presimplify, simplify } = require('topojson-simplify');
const topo = JSON.parse(readFileSync(path.join(modules, 'us-atlas/states-10m.json'), 'utf8'));

// Drop wiggles smaller than about a mile. Borders stay within a mile or two,
// which the "near a border" check in place.ts covers.
const simple = simplify(presimplify(topo), 1e-3);
const states = feature(simple, simple.objects.states).features;

const placeTs = readFileSync(path.resolve(path.dirname(out), '../lib/place.ts'), 'utf8');
const codeFor = Object.fromEntries(
  [...placeTs.matchAll(/\['([A-Z]{2})', '([^']+)'/g)].map((m) => [m[2], m[1]]),
);
codeFor['District of Columbia'] = 'DC';

const r = (n) => Math.round(n * 1000) / 1000;
const shapes = {};
for (const f of states) {
  const code = codeFor[f.properties.name];
  if (!code) continue; // territories the app doesn't cover yet
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Outer rings only: no state has a hole with another state inside it.
  shapes[code] = polys
    .map((p) => p[0].flatMap(([lon, lat]) => [r(lat), r(lon)]))
    .filter((ring) => ring.length >= 8);
}
const missing = Object.values(codeFor).filter((c) => !shapes[c]);
if (missing.length) throw new Error('No outline for ' + missing.join(', '));

writeFileSync(
  out,
  '// Generated by tools/build-state-shapes.mjs from us-atlas (US Census, public domain).\n' +
    '// Each state is a list of outlines; each outline is lat, lon, lat, lon, ...\n' +
    '// Do not edit by hand.\n' +
    'export const STATE_SHAPES: Record<string, number[][]> = ' +
    JSON.stringify(shapes) +
    ';\n',
);
console.log(Object.keys(shapes).length, 'states,', JSON.stringify(shapes).length, 'bytes');
